#!/usr/bin/env bash

# ── Inject SSH public keys (RunPod workaround for custom images) ─
# Accepts SSH_PUBLIC_KEYS (our convention), SSH_PUBLIC_KEY or PUBLIC_KEY
# (RunPod's standard env vars for key injection into custom templates).
SSH_KEYS="${SSH_PUBLIC_KEYS:-${SSH_PUBLIC_KEY:-${PUBLIC_KEY:-}}}"
if [ -n "${SSH_KEYS}" ]; then
  mkdir -p /root/.ssh
  chmod 700 /root/.ssh
  : > /root/.ssh/authorized_keys
  while IFS= read -r key; do
    [ -n "$key" ] && echo "$key" >> /root/.ssh/authorized_keys
  done <<< "${SSH_KEYS}"
  chmod 600 /root/.ssh/authorized_keys
  echo "SSH public keys injected"
fi

# ── Export container env vars for SSH login shells ──────────────
# sshd sanitizes the environment, so Docker ENV vars don't reach SSH sessions
mkdir -p /etc/profile.d
{
  echo "# Generated by entrypoint — container environment for SSH sessions"
  while IFS='=' read -r -d '' n v; do
    case "$n" in
      SSH_PUBLIC_KEYS|SSH_PUBLIC_KEY|PUBLIC_KEY|*[!A-Za-z0-9_]*) continue ;;
    esac
    printf 'export %s=%q\n' "$n" "$v"
  done < <(env -0)
} > /etc/profile.d/container-env.sh

# ── Start SSH server (non-fatal: never kill the container over sshd) ─
mkdir -p /run/sshd    # /run may be tmpfs-mounted, wiping the build-time dir
ssh-keygen -A         # generate host keys if missing
/usr/sbin/sshd || echo "WARNING: sshd failed to start"

# ── Start Ollama server in background ────────────────────────────
echo "Starting Ollama server..."
ollama serve > /tmp/ollama.log 2>&1 &
OLLAMA_PID=$!
sleep 3

# ── Pull Ollama models at startup ───────────────────────────────
echo "Pulling Ollama models (this may take a while on first run)..."
for model in glm-5.3-flash:cloud glm-5.2:cloud glm-5.3:cloud; do
    echo "  → Pulling $model..."
    ollama pull "$model" 2>&1 || echo "  ⚠ Failed to pull $model (will retry on next start)"
done
echo "Model pull complete."
echo

